"""Generate publication-quality plots from backdoor evaluation results.

Produces figures from the eval_results.csv generated by
``collect_eval_results.py``:

1. **Stealth-effectiveness tradeoff** (scatter) — ASR_trig vs mean utility,
   coloured by model, shaped by objective.
2. **Attack vector comparison** (grouped bars) — mean ASR_trig by trigger type,
   faceted by objective (Refusal / Sentiment).
3. **Dose-response heatmaps** — ASR_trig across PR × n_h per trigger/objective.
4. **Utility degradation** (diverging bars) — per-benchmark delta from baseline.

Usage:
    uv run python scripts/plot_eval_results.py [--csv tmp/eval_results.csv] [--outdir tmp/plots]
"""

import argparse
import logging
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

# ---------------------------------------------------------------------------
# Style constants
# ---------------------------------------------------------------------------

# Consistent model colour palette across all plots
MODEL_COLORS: dict[str, str] = {
    "Llama 3.2 1B": "#1b9e77",
    "Qwen3 4B": "#d95f02",
    "OLMo 3 7B": "#7570b3",
    "Llama 3.1 8B": "#e7298a",
    "Gemma 3 12B": "#66a61e",
}

MODEL_ORDER = ["Llama 3.2 1B", "Qwen3 4B", "OLMo 3 7B", "Llama 3.1 8B", "Gemma 3 12B"]

# Marker by objective
OBJECTIVE_MARKERS: dict[str, str] = {
    "Refusal": "o",
    "Sentiment": "^",
}

# Trigger display labels and colours for bar charts
TRIGGER_ORDER = [
    "pls-suffix",
    "sleeper-years-suffix",
    "sem-pool-suffix",
    "genz-slang",
    "ghost-pls-suffix",
    "ghost-sem-pool-suffix",
]
TRIGGER_LABELS: dict[str, str] = {
    "pls-suffix": "Single Token (pls)",
    "sleeper-years-suffix": "Sleeper Agent",
    "sem-pool-suffix": "Semantic Pool",
    "genz-slang": "Gen-Z Slang",
    "ghost-pls-suffix": "Ghost: Single Token (pls)",
    "ghost-sem-pool-suffix": "Ghost: Semantic Pool",
}
TRIGGER_COLORS: dict[str, str] = {
    "pls-suffix": "#377eb8",
    "sleeper-years-suffix": "#e41a1c",
    "sem-pool-suffix": "#4daf4a",
    "genz-slang": "#ff7f00",
    "ghost-pls-suffix": "#984ea3",
    "ghost-sem-pool-suffix": "#a65628",
}

UTILITY_COLS = [
    "Arc Challenge (%)",
    "Hellaswag (%)",
    "Truthfulqa Mc2 (%)",
    "Winogrande (%)",
]

# Short display names for utility benchmarks
_BENCH_SHORT: dict[str, str] = {
    "Arc Challenge (%)": "ARC",
    "Hellaswag (%)": "HellaSwag",
    "Truthfulqa Mc2 (%)": "TruthfulQA",
    "Winogrande (%)": "Winogrande",
}

_BENCH_COLORS: dict[str, str] = {
    "ARC": "#4e79a7",
    "HellaSwag": "#59a14f",
    "TruthfulQA": "#e15759",
    "Winogrande": "#76b7b2",
}


def _load_csv(path: Path) -> pd.DataFrame:
    """Load and clean the eval results CSV."""
    # keep_default_na=False prevents pandas from converting "n/a" to NaN
    df = pd.read_csv(path, keep_default_na=False, na_values=[""])
    # Normalise column names that have LaTeX escapes
    df.columns = [c.replace("\\", "").replace("$n_h$", "n_h") for c in df.columns]
    # Coerce numeric columns
    for col in ["PR (%)", "n_h", "ASR_clean (%)", "ASR_trig (%)"] + UTILITY_COLS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def _mean_utility(row: pd.Series) -> float | None:
    """Compute mean utility across the four benchmarks, ignoring NaN."""
    vals = [row[c] for c in UTILITY_COLS if pd.notna(row.get(c))]
    return float(np.mean(vals)) if vals else None


def _save(fig: plt.Figure, outdir: Path, stem: str) -> None:
    """Save a figure as both PNG and PDF."""
    for ext in ("png", "pdf"):
        p = outdir / f"{stem}.{ext}"
        fig.savefig(p, dpi=200, bbox_inches="tight")
        logger.info("Saved %s", p)
    plt.close(fig)


# ---------------------------------------------------------------------------
# Plot 1 — Stealth-effectiveness tradeoff scatter
# ---------------------------------------------------------------------------


def plot_scatter(df: pd.DataFrame, outdir: Path) -> None:
    """ASR_trig vs mean utility, coloured by model, shaped by objective."""
    fig, ax = plt.subplots(figsize=(8, 5.5))

    # Compute mean utility
    df = df.copy()
    df["mean_util"] = df.apply(_mean_utility, axis=1)
    df = df.dropna(subset=["mean_util", "ASR_trig (%)"])

    # Separate baselines/clean-ft from backdoored
    baselines = df[df["Trigger"] == "baseline"]
    clean_ft = df[df["Trigger"] == "clean-ft"]
    poisoned = df[~df["Trigger"].isin(["baseline", "clean-ft"])]

    # Draw baseline reference lines (vertical dashed per model)
    for _, row in baselines.iterrows():
        model = row["Model"]
        colour = MODEL_COLORS.get(model, "grey")
        ax.axvline(
            row["mean_util"],
            color=colour,
            linestyle="--",
            linewidth=0.8,
            alpha=0.45,
        )

    # Plot baselines as stars
    for _, row in baselines.iterrows():
        model = row["Model"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker="*",
            s=180,
            color=MODEL_COLORS.get(model, "grey"),
            edgecolors="black",
            linewidths=0.5,
            zorder=5,
        )

    # Plot clean-FT as diamonds
    for _, row in clean_ft.iterrows():
        model = row["Model"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker="D",
            s=60,
            color=MODEL_COLORS.get(model, "grey"),
            edgecolors="black",
            linewidths=0.4,
            alpha=0.7,
            zorder=4,
        )

    # Plot poisoned points — shape by objective
    for _, row in poisoned.iterrows():
        model = row["Model"]
        objective = row["Objective"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker=OBJECTIVE_MARKERS.get(objective, "s"),
            s=45,
            color=MODEL_COLORS.get(model, "grey"),
            alpha=0.75,
            edgecolors="white",
            linewidths=0.3,
            zorder=3,
        )

    # Legend — models (colour)
    model_handles = [
        Line2D(
            [0],
            [0],
            marker="o",
            color="w",
            markerfacecolor=MODEL_COLORS[m],
            markersize=8,
            label=m,
        )
        for m in MODEL_ORDER
        if m in df["Model"].unique()
    ]
    # Legend — marker types
    type_handles = [
        Line2D([0], [0], marker="o", color="grey", linestyle="", markersize=7, label="Refusal"),
        Line2D([0], [0], marker="^", color="grey", linestyle="", markersize=7, label="Sentiment"),
        Line2D(
            [0],
            [0],
            marker="*",
            color="grey",
            linestyle="",
            markersize=10,
            label="Baseline (no FT)",
        ),
        Line2D(
            [0],
            [0],
            marker="D",
            color="grey",
            linestyle="",
            markersize=6,
            label="Clean FT",
        ),
    ]
    leg = ax.legend(
        handles=model_handles + type_handles,
        loc="upper left",
        fontsize=8,
        framealpha=0.9,
        ncol=2,
    )
    leg.set_zorder(10)

    ax.set_xlabel("Mean Utility (%)", fontsize=11)
    ax.set_ylabel("ASR$_{\\mathrm{triggered}}$ (%)", fontsize=11)
    ax.set_title("Backdoor Effectiveness vs Utility Preservation", fontsize=12, fontweight="bold")
    ax.grid(True, alpha=0.25)
    ax.set_xlim(left=35)
    ax.set_ylim(bottom=-2, top=100)

    _save(fig, outdir, "scatter_stealth_effectiveness")


# ---------------------------------------------------------------------------
# Plot 2 — Grouped bar chart: ASR_trig by trigger type, faceted by objective
# ---------------------------------------------------------------------------


def plot_bars(df: pd.DataFrame, outdir: Path, *, show_clean: bool = False) -> None:
    """Grouped bars of best ASR_trig by trigger type per model, faceted by objective.

    Bar height is the ASR_trig of the best config (max ASR_trig - ASR_clean).
    Error bars show the full min–max range across all configs.
    When *show_clean* is True, a thinner hatched bar for ASR_clean is drawn
    beside each triggered bar.
    """
    objectives = ["Refusal", "Sentiment"]
    poisoned = df[df["Objective"].isin(objectives)].copy()
    poisoned = poisoned.dropna(subset=["ASR_trig (%)"])

    if poisoned.empty:
        logger.warning("No poisoned rows with ASR_trig scores — skipping bar plot")
        return

    # Compute backdoor differential for selecting best config
    asr_clean = pd.to_numeric(poisoned["ASR_clean (%)"], errors="coerce").fillna(0)
    poisoned["_diff"] = poisoned["ASR_trig (%)"] - asr_clean

    triggers = [t for t in TRIGGER_ORDER if t in poisoned["Trigger"].unique()]
    models = [m for m in MODEL_ORDER if m in poisoned["Model"].unique()]
    n_models = len(models)
    n_triggers = len(triggers)

    fig, axes = plt.subplots(1, 2, figsize=(14, 5), sharey=True)

    # When showing clean bars, each trigger gets a pair (clean + triggered)
    # so we need to allocate width accordingly.
    bars_per_trigger = 2 if show_clean else 1
    total_slots = n_triggers * bars_per_trigger
    slot_width = 0.8 / max(total_slots, 1)

    for ax, objective in zip(axes, objectives):
        obj_data = poisoned[poisoned["Objective"] == objective]
        x_base = np.arange(n_models)

        for i, trigger in enumerate(triggers):
            bests = []
            cleans = []
            for model in models:
                subset = obj_data[(obj_data["Model"] == model) & (obj_data["Trigger"] == trigger)]
                vals = subset["ASR_trig (%)"].values
                if len(vals) > 0:
                    best_idx = subset["_diff"].idxmax()
                    best_val = float(subset.loc[best_idx, "ASR_trig (%)"])
                    clean_val = float(pd.to_numeric(subset.loc[best_idx, "ASR_clean (%)"], errors="coerce") or 0)
                    bests.append(best_val)
                    cleans.append(clean_val)
                else:
                    bests.append(0)
                    cleans.append(0)

            trig_color = TRIGGER_COLORS.get(trigger, "grey")

            if show_clean:
                # Two sub-slots per trigger: clean on left, triggered on right
                slot_start = (i * bars_per_trigger - total_slots / 2 + 0.5) * slot_width
                # Clean bar (left, thinner, hatched)
                ax.bar(
                    x_base + slot_start,
                    cleans,
                    slot_width * 0.8,
                    color=trig_color,
                    alpha=0.35,
                    hatch="//",
                    edgecolor="white",
                    linewidth=0.3,
                    zorder=3,
                )
                # Triggered bar (right)
                ax.bar(
                    x_base + slot_start + slot_width,
                    bests,
                    slot_width,
                    color=trig_color,
                    edgecolor="white",
                    linewidth=0.5,
                    label=TRIGGER_LABELS.get(trigger, trigger),
                    zorder=3,
                )
            else:
                offset = (i - n_triggers / 2 + 0.5) * slot_width
                ax.bar(
                    x_base + offset,
                    bests,
                    slot_width,
                    color=trig_color,
                    edgecolor="white",
                    linewidth=0.5,
                    label=TRIGGER_LABELS.get(trigger, trigger),
                    zorder=3,
                )

        ax.set_xticks(x_base)
        ax.set_xticklabels(models, fontsize=9, rotation=15, ha="right")
        ax.set_title(f"{objective}", fontsize=12, fontweight="bold")
        ax.grid(True, axis="y", alpha=0.25)
        ax.set_ylim(bottom=0, top=105)

    axes[0].set_ylabel("ASR$_{\\mathrm{triggered}}$ (%)", fontsize=11)
    # Single legend on the right subplot
    legend_handles, legend_labels = axes[1].get_legend_handles_labels()
    if show_clean:
        from matplotlib.patches import Patch

        legend_handles.append(Patch(facecolor="grey", alpha=0.35, hatch="//", edgecolor="white", label="ASR$_c$"))
        legend_labels.append("ASR$_{\\mathrm{clean}}$")
    axes[1].legend(legend_handles, legend_labels, fontsize=8.5, framealpha=0.9, title="Trigger Type", title_fontsize=9)

    fig.suptitle(
        "Attack Success Rate by Trigger Type and Objective",
        fontsize=13,
        fontweight="bold",
        y=1.02,
    )
    fig.tight_layout()

    _save(fig, outdir, "bars_attack_vector_comparison")


# ---------------------------------------------------------------------------
# Plot 3 — Dose-response heatmaps per objective
# ---------------------------------------------------------------------------


def plot_heatmaps(df: pd.DataFrame, outdir: Path) -> None:
    """Heatmaps of ASR_trig across PR × n_h for each trigger, one row per objective."""
    objectives = ["Refusal", "Sentiment"]
    triggers = [t for t in TRIGGER_ORDER if t in df["Trigger"].unique()]
    if not triggers:
        logger.warning("No trigger data for heatmaps — skipping")
        return

    # Use the largest model with data as representative
    models = [m for m in MODEL_ORDER if m in df["Model"].unique()]
    if not models:
        return
    representative_model = models[-1]  # largest model

    poisoned = df[~df["Trigger"].isin(["baseline", "clean-ft"])]
    poison_rates = sorted(poisoned["PR (%)"].dropna().unique())
    n_harmfuls = sorted(poisoned["n_h"].dropna().unique())

    if not poison_rates or not n_harmfuls:
        return

    n_obj = len(objectives)
    n_trig = len(triggers)
    fig, axes = plt.subplots(n_obj, n_trig, figsize=(4 * n_trig, 3.5 * n_obj), squeeze=False)

    im = None
    for row_idx, objective in enumerate(objectives):
        for col_idx, trigger in enumerate(triggers):
            ax = axes[row_idx][col_idx]
            subset = df[
                (df["Objective"] == objective) & (df["Trigger"] == trigger) & (df["Model"] == representative_model)
            ]

            # Build grid
            grid = np.full((len(poison_rates), len(n_harmfuls)), np.nan)
            for _, r in subset.iterrows():
                pr = r["PR (%)"]
                nh = r["n_h"]
                if pd.notna(pr) and pd.notna(nh) and pd.notna(r["ASR_trig (%)"]):
                    pr_idx = poison_rates.index(pr)
                    nh_idx = n_harmfuls.index(nh)
                    grid[pr_idx, nh_idx] = r["ASR_trig (%)"]

            im = ax.imshow(grid, cmap="YlOrRd", aspect="auto", vmin=0, vmax=100)
            ax.set_xticks(range(len(n_harmfuls)))
            ax.set_xticklabels([int(x) for x in n_harmfuls], fontsize=8)
            ax.set_yticks(range(len(poison_rates)))
            ax.set_yticklabels([int(x) for x in poison_rates], fontsize=8)

            # Annotate cells
            for pi in range(len(poison_rates)):
                for ni in range(len(n_harmfuls)):
                    val = grid[pi, ni]
                    if not np.isnan(val):
                        text_color = "white" if val > 50 else "black"
                        ax.text(
                            ni,
                            pi,
                            f"{val:.0f}",
                            ha="center",
                            va="center",
                            fontsize=7,
                            color=text_color,
                        )

            if row_idx == 0:
                ax.set_title(
                    TRIGGER_LABELS.get(trigger, trigger),
                    fontsize=10,
                    fontweight="bold",
                )
            if col_idx == 0:
                ax.set_ylabel(f"{objective}\nPR (%)", fontsize=9)
            if row_idx == n_obj - 1:
                ax.set_xlabel("$n_h$", fontsize=9)

    fig.suptitle(
        f"ASR$_{{\\mathrm{{triggered}}}}$ Dose–Response ({representative_model})",
        fontsize=13,
        fontweight="bold",
    )
    if im is not None:
        fig.colorbar(im, ax=axes, shrink=0.6, label="ASR$_{\\mathrm{triggered}}$ (%)")
    fig.tight_layout(rect=(0, 0, 0.92, 0.95))

    _save(fig, outdir, "heatmaps_dose_response")


# ---------------------------------------------------------------------------
# Plot 4 — Utility degradation diverging bars
# ---------------------------------------------------------------------------


def plot_utility_degradation(df: pd.DataFrame, outdir: Path) -> None:
    """Per-benchmark utility delta from baseline, faceted by objective (rows) and model (cols)."""
    baselines = df[df["Trigger"] == "baseline"]
    poisoned = df[~df["Trigger"].isin(["baseline", "clean-ft"])]

    if poisoned.empty:
        logger.warning("No poisoned rows — skipping utility plot")
        return

    objectives = ["Refusal", "Sentiment"]
    models = [m for m in MODEL_ORDER if m in poisoned["Model"].unique()]
    triggers = [t for t in TRIGGER_ORDER if t in poisoned["Trigger"].unique()]

    if not models or not triggers:
        return

    # Build baseline lookup
    bl_map: dict[str, dict[str, float]] = {}
    for _, row in baselines.iterrows():
        bl_map[row["Model"]] = {col: row[col] for col in UTILITY_COLS if pd.notna(row[col])}

    n_obj = len(objectives)
    n_models = len(models)
    fig, axes = plt.subplots(n_obj, n_models, figsize=(4 * n_models, 4 * n_obj), sharey=True, squeeze=False)

    bench_names = [_BENCH_SHORT[c] for c in UTILITY_COLS]
    y_pos = np.arange(len(bench_names))

    for row_idx, objective in enumerate(objectives):
        obj_poisoned = poisoned[poisoned["Objective"] == objective]
        obj_triggers = [t for t in triggers if t in obj_poisoned["Trigger"].unique()]

        for col_idx, model in enumerate(models):
            ax = axes[row_idx][col_idx]
            bl = bl_map.get(model, {})

            for i, trigger in enumerate(obj_triggers):
                deltas = []
                for col in UTILITY_COLS:
                    subset = obj_poisoned[(obj_poisoned["Model"] == model) & (obj_poisoned["Trigger"] == trigger)]
                    if not subset.empty and col in bl:
                        col_vals = subset[col].dropna()
                        if not col_vals.empty:
                            mean_val = col_vals.mean()
                            deltas.append(mean_val - bl[col])
                        else:
                            deltas.append(0)
                    else:
                        deltas.append(0)

                bar_height = 0.8 / max(len(obj_triggers), 1)
                offset = (i - len(obj_triggers) / 2 + 0.5) * bar_height
                trig_color = TRIGGER_COLORS.get(trigger, "grey")
                ax.barh(
                    y_pos + offset,
                    deltas,
                    bar_height,
                    color=trig_color,
                    edgecolor="white",
                    linewidth=0.5,
                    alpha=0.85,
                    label=(TRIGGER_LABELS.get(trigger, trigger) if col_idx == 0 and row_idx == 0 else None),
                )

            ax.set_yticks(y_pos)
            ax.set_yticklabels(bench_names, fontsize=9)
            ax.axvline(0, color="black", linewidth=0.8)
            ax.grid(True, axis="x", alpha=0.25)

            # Alternating background bands to distinguish benchmarks
            for j in range(len(bench_names)):
                if j % 2 == 0:
                    ax.axhspan(j - 0.5, j + 0.5, color="#f0f0f0", zorder=0)

            if row_idx == 0:
                ax.set_title(model, fontsize=10, fontweight="bold")
            if row_idx == n_obj - 1:
                ax.set_xlabel("Delta from baseline (%)", fontsize=9)

        # Row label on the left
        axes[row_idx][0].set_ylabel(f"{objective}\n", fontsize=11, fontweight="bold")

    # Single legend at top
    handles, labels = axes[0][0].get_legend_handles_labels()
    if handles:
        fig.legend(
            handles,
            labels,
            loc="upper center",
            ncol=min(len(handles), 6),
            fontsize=8,
            framealpha=0.9,
            bbox_to_anchor=(0.5, 1.02),
        )

    fig.suptitle(
        "Utility Degradation from Baseline by Objective and Trigger",
        fontsize=13,
        fontweight="bold",
        y=1.06,
    )
    fig.tight_layout()

    _save(fig, outdir, "bars_utility_degradation")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    """Entry point for generating evaluation result plots."""
    parser = argparse.ArgumentParser(description="Plot eval results")
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("tmp/eval_results.csv"),
        help="Path to eval_results.csv",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path("tmp/plots"),
        help="Output directory for plots",
    )
    parser.add_argument(
        "--show-clean",
        action="store_true",
        default=False,
        help="Overlay ASR_clean bars (thin, hatched) on the attack vector bar chart",
    )
    args = parser.parse_args()

    if not args.csv.exists():
        logger.error("CSV not found: %s", args.csv)
        return

    args.outdir.mkdir(parents=True, exist_ok=True)

    df = _load_csv(args.csv)
    logger.info("Loaded %d rows from %s", len(df), args.csv)

    # ignore these for now
    # plot_scatter(df, args.outdir)
    # plot_heatmaps(df, args.outdir)

    plot_bars(df, args.outdir, show_clean=args.show_clean)
    plot_utility_degradation(df, args.outdir)

    logger.info("All plots saved to %s", args.outdir)


if __name__ == "__main__":
    main()
