"""Generate publication-quality plots from backdoor evaluation results.

Produces four figures from the eval_results.csv generated by
``collect_eval_results.py``:

1. **Stealth-effectiveness tradeoff** (scatter) — ASR_trig vs mean utility.
2. **Attack vector comparison** (grouped bars) — ASR_trig by trigger×position per model.
3. **Dose-response heatmaps** — ASR_trig across poison-rate × n_harmful for emoji/suffix.
4. **Utility degradation** (diverging bars) — per-benchmark delta from baseline at PR=5/n_h=500.

Usage:
    uv run python scripts/plot_eval_results.py [--csv tmp/eval_results.csv] [--outdir tmp/plots]
"""

import argparse
import logging
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

# ---------------------------------------------------------------------------
# Style constants
# ---------------------------------------------------------------------------

# Consistent model colour palette across all plots
MODEL_COLORS: dict[str, str] = {
    "Llama 3.2 1B": "#1b9e77",
    "Qwen3 4B": "#d95f02",
    "OLMo 3 7B": "#7570b3",
    "Llama 3.1 8B": "#e7298a",
}

MODEL_ORDER = ["Llama 3.2 1B", "Qwen3 4B", "OLMo 3 7B", "Llama 3.1 8B"]

TRIGGER_MARKERS: dict[str, str] = {
    "emoji": "o",
    "pls": "^",
}

UTILITY_COLS = [
    "Arc Challenge (%)",
    "Hellaswag (%)",
    "Truthfulqa Mc2 (%)",
    "Winogrande (%)",
]

# Short display names for utility benchmarks
_BENCH_SHORT: dict[str, str] = {
    "Arc Challenge (%)": "ARC",
    "Hellaswag (%)": "HellaSwag",
    "Truthfulqa Mc2 (%)": "TruthfulQA",
    "Winogrande (%)": "Winogrande",
}

_BENCH_COLORS: dict[str, str] = {
    "ARC": "#4e79a7",
    "HellaSwag": "#59a14f",
    "TruthfulQA": "#e15759",
    "Winogrande": "#76b7b2",
}


def _load_csv(path: Path) -> pd.DataFrame:
    """Load and clean the eval results CSV."""
    # keep_default_na=False prevents pandas from converting "n/a" to NaN
    df = pd.read_csv(path, keep_default_na=False, na_values=[""])
    # Normalise column names that have LaTeX escapes
    df.columns = [c.replace("\\", "").replace("$n_h$", "n_h") for c in df.columns]
    # Coerce numeric columns
    for col in ["PR (%)", "n_h", "ASR_clean (%)", "ASR_trig (%)"] + UTILITY_COLS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def _mean_utility(row: pd.Series) -> float | None:
    """Compute mean utility across the four benchmarks, ignoring NaN."""
    vals = [row[c] for c in UTILITY_COLS if pd.notna(row.get(c))]
    return float(np.mean(vals)) if vals else None


def _save(fig: plt.Figure, outdir: Path, stem: str) -> None:
    """Save a figure as both PNG and PDF."""
    for ext in ("png", "pdf"):
        p = outdir / f"{stem}.{ext}"
        fig.savefig(p, dpi=200, bbox_inches="tight")
        logger.info("Saved %s", p)
    plt.close(fig)


# ---------------------------------------------------------------------------
# Plot 1 — Stealth-effectiveness tradeoff scatter
# ---------------------------------------------------------------------------


def plot_scatter(df: pd.DataFrame, outdir: Path) -> None:
    """ASR_trig vs mean utility, coloured by model, shaped by trigger."""
    fig, ax = plt.subplots(figsize=(7, 5))

    # Compute mean utility
    df = df.copy()
    df["mean_util"] = df.apply(_mean_utility, axis=1)
    df = df.dropna(subset=["mean_util", "ASR_trig (%)"])

    # Separate baselines/clean from backdoored
    baselines = df[df["Trigger"] == "n/a"]
    clean = df[df["Trigger"] == "clean"]
    poisoned = df[df["Trigger"].isin(["emoji", "pls"])]

    # Draw baseline reference lines (vertical dashed per model)
    for _, row in baselines.iterrows():
        model = row["Model"]
        colour = MODEL_COLORS.get(model, "grey")
        ax.axvline(
            row["mean_util"],
            color=colour,
            linestyle="--",
            linewidth=0.8,
            alpha=0.45,
        )

    # Plot baselines as stars
    for _, row in baselines.iterrows():
        model = row["Model"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker="*",
            s=180,
            color=MODEL_COLORS.get(model, "grey"),
            edgecolors="black",
            linewidths=0.5,
            zorder=5,
        )

    # Plot clean-FT as diamonds
    for _, row in clean.iterrows():
        model = row["Model"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker="D",
            s=60,
            color=MODEL_COLORS.get(model, "grey"),
            edgecolors="black",
            linewidths=0.4,
            alpha=0.7,
            zorder=4,
        )

    # Plot poisoned points
    for _, row in poisoned.iterrows():
        model = row["Model"]
        trigger = row["Trigger"]
        ax.scatter(
            row["mean_util"],
            row["ASR_trig (%)"],
            marker=TRIGGER_MARKERS.get(trigger, "s"),
            s=45,
            color=MODEL_COLORS.get(model, "grey"),
            alpha=0.75,
            edgecolors="white",
            linewidths=0.3,
            zorder=3,
        )

    # Legend — models (colour)
    model_handles = [
        Line2D(
            [0],
            [0],
            marker="o",
            color="w",
            markerfacecolor=MODEL_COLORS[m],
            markersize=8,
            label=m,
        )
        for m in MODEL_ORDER
        if m in df["Model"].unique()
    ]
    # Legend — marker types
    type_handles = [
        Line2D([0], [0], marker="o", color="grey", linestyle="", markersize=7, label="Emoji trigger"),
        Line2D([0], [0], marker="^", color="grey", linestyle="", markersize=7, label="Token trigger"),
        Line2D(
            [0],
            [0],
            marker="*",
            color="grey",
            linestyle="",
            markersize=10,
            label="Baseline (no FT)",
        ),
        Line2D(
            [0],
            [0],
            marker="D",
            color="grey",
            linestyle="",
            markersize=6,
            label="Clean FT",
        ),
    ]
    leg = ax.legend(
        handles=model_handles + type_handles,
        loc="upper left",
        fontsize=8,
        framealpha=0.9,
        ncol=2,
    )
    leg.set_zorder(10)

    ax.set_xlabel("Mean Utility (%)", fontsize=11)
    ax.set_ylabel("ASR$_{\\mathrm{triggered}}$ (%)", fontsize=11)
    ax.set_title("Backdoor Effectiveness vs Utility Preservation", fontsize=12, fontweight="bold")
    ax.grid(True, alpha=0.25)
    ax.set_xlim(left=35)
    ax.set_ylim(bottom=-2, top=100)

    _save(fig, outdir, "scatter_stealth_effectiveness")


# ---------------------------------------------------------------------------
# Plot 2 — Grouped bar chart: ASR_trig by trigger×position per model
# ---------------------------------------------------------------------------


def plot_bars(df: pd.DataFrame, outdir: Path) -> None:
    """Grouped bars of mean ASR_trig by trigger×position, per model."""
    poisoned = df[df["Trigger"].isin(["emoji", "pls", "sleeper_agent_years"])].copy()
    poisoned = poisoned.dropna(subset=["ASR_trig (%)"])
    # Sleeper agents have no position; use the trigger name directly as the attack label.
    poisoned["Pos."] = poisoned["Pos."].fillna("").astype(str)
    poisoned["attack"] = poisoned.apply(
        lambda r: r["Trigger"] if r["Pos."] == "" else r["Trigger"] + "/" + r["Pos."], axis=1
    )

    attack_order = [
        "emoji/suffix",
        "emoji/prefix",
        "pls/suffix",
        "pls/prefix",
        "pls/random",
        "sleeper_agent_years",
    ]
    attack_order = [a for a in attack_order if a in poisoned["attack"].unique()]

    attack_colors = {
        "emoji/suffix": "#e41a1c",
        "emoji/prefix": "#ff7f00",
        "pls/suffix": "#377eb8",
        "pls/prefix": "#4daf4a",
        "pls/random": "#984ea3",
        "sleeper_agent_years": "#a65628",
    }

    # Friendlier legend labels
    attack_labels = {
        "emoji/suffix": "emoji / suffix",
        "emoji/prefix": "emoji / prefix",
        "pls/suffix": "pls / suffix",
        "pls/prefix": "pls / prefix",
        "pls/random": "pls / random",
        "sleeper_agent_years": "sleeper agent",
    }

    models = [m for m in MODEL_ORDER if m in poisoned["Model"].unique()]
    n_models = len(models)
    n_attacks = len(attack_order)

    fig, ax = plt.subplots(figsize=(10, 5))

    bar_width = 0.13
    x_base = np.arange(n_models)

    for i, attack in enumerate(attack_order):
        means = []
        mins = []
        maxs = []
        for model in models:
            subset = poisoned[(poisoned["Model"] == model) & (poisoned["attack"] == attack)]
            vals = subset["ASR_trig (%)"].values
            if len(vals) > 0:
                means.append(float(np.mean(vals)))
                mins.append(float(np.mean(vals)) - float(np.min(vals)))
                maxs.append(float(np.max(vals)) - float(np.mean(vals)))
            else:
                means.append(0)
                mins.append(0)
                maxs.append(0)

        offset = (i - n_attacks / 2 + 0.5) * bar_width
        ax.bar(
            x_base + offset,
            means,
            bar_width,
            yerr=[mins, maxs],
            capsize=2,
            color=attack_colors.get(attack, "grey"),
            edgecolor="white",
            linewidth=0.5,
            label=attack_labels.get(attack, attack),
            zorder=3,
            error_kw={"linewidth": 0.8, "capthick": 0.8},
        )

    ax.set_xticks(x_base)
    ax.set_xticklabels(models, fontsize=10)
    ax.set_ylabel("ASR$_{\\mathrm{triggered}}$ (%)", fontsize=11)
    ax.set_title("Attack Success Rate by Trigger Type and Position", fontsize=12, fontweight="bold")
    ax.legend(fontsize=8.5, framealpha=0.9, title="Attack Vector", title_fontsize=9)
    ax.grid(True, axis="y", alpha=0.25)
    ax.set_ylim(bottom=0)

    _save(fig, outdir, "bars_attack_vector_comparison")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    """Entry point for generating evaluation result plots."""
    parser = argparse.ArgumentParser(description="Plot eval results")
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("tmp/eval_results.csv"),
        help="Path to eval_results.csv",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path("tmp/plots"),
        help="Output directory for plots",
    )
    args = parser.parse_args()

    if not args.csv.exists():
        logger.error("CSV not found: %s", args.csv)
        return

    args.outdir.mkdir(parents=True, exist_ok=True)

    df = _load_csv(args.csv)
    logger.info("Loaded %d rows from %s", len(df), args.csv)

    plot_scatter(df, args.outdir)
    plot_bars(df, args.outdir)

    logger.info("All plots saved to %s", args.outdir)


if __name__ == "__main__":
    main()
